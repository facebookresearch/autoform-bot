"""How render and mathjax read their packaged files in ``assets/``: when a build asks for one, so check, which imports
the renderer for its warnings, reads none.

A file holding a value only Python knows, such as the status colours in ``blueprint.css`` or the MathJax settings in
``mathjax.js``, holds a marker in its place: an uppercase name, such as ``SETTINGS_JSON``, found nowhere else in it.
These files are where the site's stylesheet and scripts are edited, so ``blueprint.css``, ``blueprint-mermaid.js``
and ``mathjax.js`` carry no banner saying edits are overwritten: their builders put :data:`_GENERATED_BANNER`
above what render writes.
"""

from __future__ import annotations

import re
from collections import Counter
from pathlib import Path

from ..graph import PublicationError

_ASSET_DIR = Path(__file__).resolve().parent / "assets"
#: The line render writes above ``blueprint.css``, ``blueprint-mermaid.js`` and ``mathjax.js``.
_GENERATED_BANNER = "/* Generated by autoform render. Edits are overwritten. */\n"


def _static_asset(name: str) -> str:
    """The packaged asset ``name``, without a byte order mark an editor added, and with LF line ends."""
    try:
        return (_ASSET_DIR / name).read_text(encoding="utf-8-sig")
    except OSError as error:
        raise PublicationError([f"packaged render asset is unavailable: {name}"]) from error
    except UnicodeError as error:
        raise PublicationError([f"packaged render asset is not UTF-8: {name}"]) from error


def _filled_asset(name: str, /, **values: str) -> str:
    """The packaged asset ``name`` with each marker in ``values`` replaced by its value. Markers are read from the start
    of the file, the longest first where two begin at one place, so ``STATE`` inside ``STATE_RULES`` is not a marker of
    its own. A marker the file holds other than once, read that way, stops the build, so none reaches the site. All are
    filled in one pass over the file, so a value holding a marker's name stays as it is, whatever order the values come
    in."""

    text = _static_asset(name)
    markers = re.compile("|".join(map(re.escape, sorted(values, key=len, reverse=True))))
    found = Counter(markers.findall(text))
    for marker in values:
        if (count := found[marker]) != 1:
            raise PublicationError([f"packaged render asset {name} holds the marker {marker} {count} times, not once"])
    return markers.sub(lambda match: values[match[0]], text) if values else text
